const originalText = new Map<Text, string>();
const originalAttrs = new Map<Element, Map<string, string>>();
let observer: MutationObserver | null = null;
let activeLanguage: Language = 'zh';
let applying = false;
const ATTRS = ['title', 'aria-label', 'placeholder'] as const;

const translateValue = (value: string): string => {
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  const leading = match?.[1] ?? '';
  const core = match?.[2] ?? value;
  const trailing = match?.[3] ?? '';
  if (!/[\u4e00-\u9fff]/.test(core)) return value;
  const exact = EXACT[core];
  if (exact !== undefined) return `${leading}${exact}${trailing}`;
  for (const [pattern, replacer] of PATTERNS) {
    const parts = core.match(pattern);
    if (parts) return `${leading}${replacer(...parts)}${trailing}`;
  }
  return value;
};

const shouldSkipText = (node: Text): boolean => {
  const parent = node.parentElement;
  if (!parent) return true;
  return Boolean(parent.closest('script, style, textarea, [contenteditable="true"]'));
};

const translateTextNode = (node: Text) => {
  if (shouldSkipText(node)) return;
  const current = node.nodeValue ?? '';
  if (!/[\u4e00-\u9fff]/.test(current)) return;
  const translated = translateValue(current);
  if (translated === current) return;
  originalText.set(node, current);
  node.nodeValue = translated;
};

const translateElementAttrs = (element: Element) => {
  for (const attr of ATTRS) {
    const current = element.getAttribute(attr);
    if (!current || !/[\u4e00-\u9fff]/.test(current)) continue;
    const translated = translateValue(current);
    if (translated === current) continue;
    let stored = originalAttrs.get(element);
    if (!stored) {
      stored = new Map<string, string>();
      originalAttrs.set(element, stored);
    }
    stored.set(attr, current);
    element.setAttribute(attr, translated);
  }
};

const translateTree = (root: Node) => {
  if (activeLanguage !== 'en') return;
  applying = true;
  try {
    if (root.nodeType === Node.TEXT_NODE) translateTextNode(root as Text);
    if (root.nodeType === Node.ELEMENT_NODE) translateElementAttrs(root as Element);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
      else translateElementAttrs(node as Element);
      node = walker.nextNode();
    }
  } finally {
    applying = false;
  }
};

const restoreChinese = () => {
  applying = true;
  try {
    for (const [node, value] of originalText) {
      if (node.isConnected) node.nodeValue = value;
    }
    for (const [element, attrs] of originalAttrs) {
      if (element.isConnected) attrs.forEach((value, attr) => element.setAttribute(attr, value));
    }
    originalText.clear();
    originalAttrs.clear();
  } finally {
    applying = false;
  }
};

export const applyRuntimeEnglishLocalization = (language: Language): (() => void) => {
  activeLanguage = language;
  if (typeof document === 'undefined' || typeof MutationObserver === 'undefined') return () => undefined;

  if (observer) {
    observer.disconnect();
    observer = null;
  }

  if (language === 'zh') {
    restoreChinese();
    return () => undefined;
  }

  translateTree(document.body);
  observer = new MutationObserver((mutations) => {
    if (applying || activeLanguage !== 'en') return;
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateTree(mutation.target);
      if (mutation.type === 'attributes' && mutation.target instanceof Element) translateElementAttrs(mutation.target);
      mutation.addedNodes.forEach((node) => translateTree(node));
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...ATTRS],
  });

  return () => {
    observer?.disconnect();
    observer = null;
  };
};
